 JMP MANUAL_FINISH

MANUAL_EW:

 CMP CLOSE_EW,1
 JNE MANUAL_EW_RUN

 LEA DX,INVALID_TEXT
 CALL PRINT_TEXT

 JMP MANUAL_MODE

MANUAL_EW_RUN:

 CALL SET_EW_TIMING
