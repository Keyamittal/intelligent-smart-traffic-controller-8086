 MOV AL,2
 CALL COUNTDOWN

 JMP MANUAL_FINISH

MANUAL_INVALID:

 LEA DX,INVALID_TEXT
 CALL PRINT_TEXT

 JMP MANUAL_MODE

MANUAL_EXIT:

 JMP MAIN_MENU

RUN_MANUAL_NS:

 MOV INTERRUPTED,0

 MOV AX,0249h
 OUT 4,AX

 MOV AL,2
 CALL COUNTDOWN

 CMP INTERRUPTED,1
 JE MANUAL_NS_RETURN

 MOV AX,0861h
 OUT 4,AX

 LEA DX,NS_GREEN_TEXT
 CALL PRINT_TEXT

 MOV AL,GREEN_TIME
 CALL COUNTDOWN

 CMP INTERRUPTED,1
 JE MANUAL_NS_RETURN

 MOV AX,0451h
 OUT 4,AX

 LEA DX,NS_YELLOW_TEXT
 CALL PRINT_TEXT

 MOV AL,YELLOW_TIME
 CALL COUNTDOWN

 CMP INTERRUPTED,1
 JE MANUAL_NS_RETURN

 MOV AX,0249h
 OUT 4,AX

 LEA DX,ALL_RED_TEXT
 CALL PRINT_TEXT

 MOV AL,2
 CALL COUNTDOWN

MANUAL_NS_RETURN:

 RET

RUN_MANUAL_EW:

 MOV INTERRUPTED,0

 MOV AX,0249h
 OUT 4,AX

 MOV AL,2
 CALL COUNTDOWN

 CMP INTERRUPTED,1
 JE MANUAL_EW_RETURN

 MOV AX,030Ch
 OUT 4,AX

 LEA DX,EW_GREEN_TEXT
 CALL PRINT_TEXT

 MOV AL,GREEN_TIME
 CALL COUNTDOWN

 CMP INTERRUPTED,1
 JE MANUAL_EW_RETURN

 MOV AX,028Ah
 OUT 4,AX

 LEA DX,EW_YELLOW_TEXT
 CALL PRINT_TEXT

 MOV AL,YELLOW_TIME
 CALL COUNTDOWN

 CMP INTERRUPTED,1
 JE MANUAL_EW_RETURN

 MOV AX,0249h
 OUT 4,AX

 LEA DX,ALL_RED_TEXT
 CALL PRINT_TEXT

 MOV AL,2
 CALL COUNTDOWN

MANUAL_EW_RETURN:

 RET

MANUAL_FINISH:

 MOV INTERRUPTED,0

 MOV AX,0249h
 OUT 4,AX

 LEA DX,MANUAL_DONE
 CALL PRINT_TEXT

 JMP MAIN_MENU

