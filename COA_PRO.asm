START:

 PUSH CS
 POP DS

 MOV AX,0249h
 OUT 4,AX

; ==========================================
; MAIN MENU
; ==========================================

MAIN_MENU:

 MOV AX,0249h
 OUT 4,AX

 LEA DX,TITLE_TEXT
 CALL PRINT_TEXT

 LEA DX,MENU_TEXT
 CALL PRINT_TEXT

 CALL READ_KEY

 CMP AL,'0'
 JNE MENU_1
 JMP EXIT_PROGRAM

MENU_1:
 CMP AL,'1'
 JNE MENU_2
 JMP AUTOMATIC_MODE

MENU_2:
 CMP AL,'2'
 JNE MENU_3
 JMP TRAFFIC_INPUT

MENU_3:
 CMP AL,'3'
 JNE MENU_4
 JMP EMERGENCY_MODE

MENU_4:
 CMP AL,'4'
 JNE MENU_5
 JMP PEDESTRIAN_MODE

MENU_5:
 CMP AL,'5'
 JNE MENU_6
 JMP NIGHT_MODE_TOGGLE

MENU_6:
 CMP AL,'6'
 JNE MENU_7
 JMP MANUAL_MODE

MENU_7:
 CMP AL,'7'
 JNE MENU_8
 JMP SCHEDULE_SELECTION

MENU_8:
 CMP AL,'8'
 JNE MENU_9
 JMP FAULT_SELECTION

MENU_9:
 CMP AL,'9'
 JNE MENU_A
 JMP CLOSURE_SELECTION

MENU_A:
 CMP AL,'A'
 JE SHOW_REPORT

 CMP AL,'a'
 JE SHOW_REPORT

 CMP AL,'B'
 JE SHOW_SETTINGS

 CMP AL,'b'
 JE SHOW_SETTINGS

 JMP INVALID_SELECTION

INVALID_SELECTION:

 LEA DX,INVALID_TEXT
 CALL PRINT_TEXT

 JMP MAIN_MENU

; ==========================================
; FEATURE 1 AND 4
; TRAFFIC CATEGORY INPUT
; ==========================================

TRAFFIC_INPUT:

 LEA DX,ASK_NS
 CALL PRINT_TEXT

 CALL READ_KEY

 CMP AL,'1'
 JB TRAFFIC_INVALID

 CMP AL,'3'
 JA TRAFFIC_INVALID

 SUB AL,'0'
 MOV NS_CAT,AL

 LEA DX,ASK_EW
 CALL PRINT_TEXT

 CALL READ_KEY

 CMP AL,'1'
 JB TRAFFIC_INVALID

 CMP AL,'3'
 JA TRAFFIC_INVALID

 SUB AL,'0'
 MOV EW_CAT,AL

 LEA DX,TRAFFIC_SAVED
 CALL PRINT_TEXT

 JMP MAIN_MENU

TRAFFIC_INVALID:

 JMP INVALID_SELECTION

; ==========================================
; FEATURE 5
; NIGHT MODE
; ==========================================

NIGHT_MODE_TOGGLE:

 XOR NIGHT_MODE,1

 CMP NIGHT_MODE,1
 JNE NIGHT_DISABLED

 LEA DX,NIGHT_ON
 CALL PRINT_TEXT

 JMP MAIN_MENU

NIGHT_DISABLED:

 LEA DX,NIGHT_OFF
 CALL PRINT_TEXT

 JMP MAIN_MENU

; ==========================================
; FEATURE 9
; PEAK / OFF-PEAK SCHEDULING
; ==========================================

SCHEDULE_SELECTION:

 LEA DX,SCHEDULE_TEXT
 CALL PRINT_TEXT

 CALL READ_KEY

 CMP AL,'1'
 JB SCHEDULE_INVALID

 CMP AL,'4'
 JA SCHEDULE_INVALID

 SUB AL,'0'
 MOV SCHEDULE_MODE,AL

 LEA DX,SCHEDULE_DONE
 CALL PRINT_TEXT

 JMP MAIN_MENU

SCHEDULE_INVALID:

 JMP INVALID_SELECTION

; ==========================================
; FEATURE 8
; FAULT DETECTION
; ==========================================

FAULT_SELECTION:

 LEA DX,FAULT_MENU
 CALL PRINT_TEXT

 CALL READ_KEY

 CMP AL,'5'
 JE FAULT_CLEAR

 CMP AL,'1'
 JB FAULT_INVALID

 CMP AL,'4'
 JA FAULT_INVALID

 MOV FAULT_ACTIVE,1

 MOV AX,0249h
 OUT 4,AX

 LEA DX,FAULT_TEXT
 CALL PRINT_TEXT

 JMP MAIN_MENU

FAULT_CLEAR:

 MOV FAULT_ACTIVE,0

 LEA DX,FAULT_CLEAR_TEXT
 CALL PRINT_TEXT

 JMP MAIN_MENU

FAULT_INVALID:

 JMP INVALID_SELECTION

; ==========================================
; FEATURE 9
; ROAD CLOSURE
; ==========================================

CLOSURE_SELECTION:

 LEA DX,CLOSURE_MENU
 CALL PRINT_TEXT

 CALL READ_KEY

 CMP AL,'1'
 JE CLOSE_NS_ROAD

 CMP AL,'2'
 JE CLOSE_EW_ROAD

 CMP AL,'3'
 JE OPEN_ALL_ROADS

 JMP INVALID_SELECTION

CLOSE_NS_ROAD:

 MOV CLOSE_NS,1
 MOV CLOSE_EW,0

 JMP CLOSURE_SAVED

CLOSE_EW_ROAD:

 MOV CLOSE_EW,1
 MOV CLOSE_NS,0

 JMP CLOSURE_SAVED

OPEN_ALL_ROADS:

 MOV CLOSE_NS,0
 MOV CLOSE_EW,0

CLOSURE_SAVED:

 LEA DX,CLOSURE_DONE
 CALL PRINT_TEXT

 JMP MAIN_MENU

; ==========================================
; FEATURE 3
; PEDESTRIAN CROSSING
; ==========================================

PEDESTRIAN_MODE:

 MOV INTERRUPTED,0
 MOV PED_PENDING,0

 MOV AX,0249h
 OUT 4,AX

 LEA DX,PEDESTRIAN_TEXT
 CALL PRINT_TEXT

 MOV AL,45
 CALL COUNTDOWN

 CMP INTERRUPTED,1
 JE PED_INTERRUPTED

 INC PED_COUNT

 LEA DX,PEDESTRIAN_DONE
 CALL PRINT_TEXT

PED_INTERRUPTED:

 MOV INTERRUPTED,0

 MOV AX,0249h
 OUT 4,AX

 JMP MAIN_MENU

; ==========================================
; FEATURE 1
; AUTOMATIC ADAPTIVE CONTROL
; ONE COMPLETE CYCLE THEN MENU
; ==========================================

AUTOMATIC_MODE:

 MOV INTERRUPTED,0

 CMP FAULT_ACTIVE,0
 JE AUTO_CHECK_CLOSURE

 LEA DX,FAULT_WARNING
 CALL PRINT_TEXT

 JMP MAIN_MENU

AUTO_CHECK_CLOSURE:

 CMP CLOSE_NS,1
 JNE AUTO_CHECK_EW

 CMP CLOSE_EW,1
 JNE AUTO_ONLY_EW

 LEA DX,BOTH_CLOSED_TEXT
 CALL PRINT_TEXT

 JMP MAIN_MENU

AUTO_ONLY_EW:

 CALL RUN_EW_PHASE

 CMP INTERRUPTED,1
 JE AUTO_INTERRUPTED

 JMP AUTO_FINISH

AUTO_CHECK_EW:

 CMP CLOSE_EW,1
 JNE AUTO_BOTH

 CALL RUN_NS_PHASE

 CMP INTERRUPTED,1
 JE AUTO_INTERRUPTED

 JMP AUTO_FINISH

AUTO_BOTH:

 CALL RUN_NS_PHASE

 CMP INTERRUPTED,1
 JE AUTO_INTERRUPTED

 CALL RUN_EW_PHASE

 CMP INTERRUPTED,1
 JE AUTO_INTERRUPTED

AUTO_FINISH:

 INC TOTAL_CYCLES

 JMP MAIN_MENU

AUTO_INTERRUPTED:

 MOV INTERRUPTED,0

 MOV AX,0249h
 OUT 4,AX

 LEA DX,INTERRUPT_TEXT
 CALL PRINT_TEXT

 JMP MAIN_MENU

; ==========================================
; NORTH-SOUTH PHASE
; ==========================================

RUN_NS_PHASE:

 CALL SET_NS_TIMING

 MOV AX,0249h
 OUT 4,AX

 LEA DX,ALL_RED_TEXT
 CALL PRINT_TEXT

 MOV AL,2
 CALL COUNTDOWN

 CMP INTERRUPTED,1
 JE NS_RETURN

 MOV AX,0861h
 OUT 4,AX

 LEA DX,NS_GREEN_TEXT
 CALL PRINT_TEXT

 MOV AL,GREEN_TIME
 CALL COUNTDOWN

 CMP INTERRUPTED,1
 JE NS_RETURN

 MOV AX,0451h
 OUT 4,AX

 LEA DX,NS_YELLOW_TEXT
 CALL PRINT_TEXT

 MOV AL,YELLOW_TIME
 CALL COUNTDOWN

 CMP INTERRUPTED,1
 JE NS_RETURN

 MOV AX,0249h
 OUT 4,AX

 LEA DX,ALL_RED_TEXT
 CALL PRINT_TEXT

 MOV AL,2
 CALL COUNTDOWN

 CMP INTERRUPTED,1
 JE NS_RETURN

 INC NS_COUNT

 MOV AL,NS_CAT
 CALL ADD_VEHICLES

 CMP PED_PENDING,1
 JNE NS_RETURN

 CALL RUN_PEDESTRIAN

 MOV INTERRUPTED,1

NS_RETURN:

 RET

; ==========================================
; EAST-WEST PHASE
; ==========================================

RUN_EW_PHASE:

 CALL SET_EW_TIMING

 MOV AX,0249h
 OUT 4,AX

 LEA DX,ALL_RED_TEXT
 CALL PRINT_TEXT

 MOV AL,2
 CALL COUNTDOWN

 CMP INTERRUPTED,1
 JE EW_RETURN

 MOV AX,030Ch
 OUT 4,AX

 LEA DX,EW_GREEN_TEXT
 CALL PRINT_TEXT

 MOV AL,GREEN_TIME
 CALL COUNTDOWN

 CMP INTERRUPTED,1
 JE EW_RETURN

 MOV AX,028Ah
 OUT 4,AX

 LEA DX,EW_YELLOW_TEXT
 CALL PRINT_TEXT

 MOV AL,YELLOW_TIME
 CALL COUNTDOWN

 CMP INTERRUPTED,1
 JE EW_RETURN

 MOV AX,0249h
 OUT 4,AX

 LEA DX,ALL_RED_TEXT
 CALL PRINT_TEXT

 MOV AL,2
 CALL COUNTDOWN

 CMP INTERRUPTED,1
 JE EW_RETURN

 INC EW_COUNT

 MOV AL,EW_CAT
 CALL ADD_VEHICLES

 CMP PED_PENDING,1
 JNE EW_RETURN

 CALL RUN_PEDESTRIAN

 MOV INTERRUPTED,1

EW_RETURN:

 RET

; ==========================================
; ADAPTIVE TIMING
; ==========================================

SET_NS_TIMING:

 MOV AL,NS_CAT
 JMP CALCULATE_TIMING

SET_EW_TIMING:

 MOV AL,EW_CAT

CALCULATE_TIMING:

 CMP AL,1
 JNE CHECK_MEDIUM

 MOV GREEN_TIME,30
 MOV YELLOW_TIME,5

 JMP APPLY_SCHEDULE

CHECK_MEDIUM:

 CMP AL,2
 JNE SET_HIGH

 MOV GREEN_TIME,40
 MOV YELLOW_TIME,7

 JMP APPLY_SCHEDULE

SET_HIGH:

 MOV GREEN_TIME,45
 MOV YELLOW_TIME,10

APPLY_SCHEDULE:

 CMP NIGHT_MODE,1
 JE FORCE_LOW

 CMP SCHEDULE_MODE,4
 JE FORCE_LOW

 CMP SCHEDULE_MODE,1
 JE FORCE_HIGH

 CMP SCHEDULE_MODE,3
 JE FORCE_HIGH

 RET

FORCE_LOW:

 MOV GREEN_TIME,30
 MOV YELLOW_TIME,5

 RET

FORCE_HIGH:

 MOV GREEN_TIME,45
 MOV YELLOW_TIME,10

 RET

; ==========================================
; FEATURE 3
; PEDESTRIAN PHASE ROUTINE
; ==========================================

RUN_PEDESTRIAN:

 MOV PED_PENDING,0

 MOV AX,0249h
 OUT 4,AX

 LEA DX,PEDESTRIAN_TEXT
 CALL PRINT_TEXT

 MOV AL,45
 CALL COUNTDOWN

 CMP INTERRUPTED,1
 JE PED_ROUTINE_RETURN

 INC PED_COUNT

PED_ROUTINE_RETURN:

 MOV AX,0249h
 OUT 4,AX

 RET

; ==========================================
; FEATURE 2
; EMERGENCY PRIORITY
; ==========================================

EMERGENCY_MODE:

 MOV INTERRUPTED,0

 CMP FAULT_ACTIVE,0
 JE EM_ASK_DIRECTION

 LEA DX,FAULT_WARNING
 CALL PRINT_TEXT

 JMP MAIN_MENU

EM_ASK_DIRECTION:

 LEA DX,ASK_DIRECTION
 CALL PRINT_TEXT

 CALL READ_KEY

 CMP AL,'1'
 JB EM_INVALID

 CMP AL,'4'
 JA EM_INVALID

 MOV EMERGENCY_DIR,AL

 MOV AX,0249h
 OUT 4,AX

 LEA DX,EMERGENCY_TEXT
 CALL PRINT_TEXT

 MOV AL,2
 CALL COUNTDOWN

 CMP INTERRUPTED,1
 JE EM_RETURN

 CMP EMERGENCY_DIR,'1'
 JE EM_NORTH

 CMP EMERGENCY_DIR,'2'
 JE EM_SOUTH

 CMP EMERGENCY_DIR,'3'
 JE EM_EAST

 JMP EM_WEST

EM_NORTH:

 MOV AX,0261h
 JMP EM_GREEN_PHASE

EM_SOUTH:

 MOV AX,0849h
 JMP EM_GREEN_PHASE

EM_EAST:

 MOV AX,024Ch
 JMP EM_GREEN_PHASE

EM_WEST:

 MOV AX,0309h

EM_GREEN_PHASE:

 OUT 4,AX

 MOV AL,60
 CALL COUNTDOWN

 CMP INTERRUPTED,1
 JE EM_RETURN

 CMP EMERGENCY_DIR,'1'
 JE EM_N_YELLOW

 CMP EMERGENCY_DIR,'2'
 JE EM_S_YELLOW

 CMP EMERGENCY_DIR,'3'
 JE EM_E_YELLOW

 MOV AX,0289h
 JMP EM_YELLOW_PHASE

EM_N_YELLOW:

 MOV AX,0251h
 JMP EM_YELLOW_PHASE

EM_S_YELLOW:

 MOV AX,0449h
 JMP EM_YELLOW_PHASE

EM_E_YELLOW:

 MOV AX,024Ah

EM_YELLOW_PHASE:

 OUT 4,AX

 MOV AL,5
 CALL COUNTDOWN

 CMP INTERRUPTED,1
 JE EM_RETURN

 MOV AX,0249h
 OUT 4,AX

 MOV AL,2
 CALL COUNTDOWN

 CMP INTERRUPTED,1
 JE EM_RETURN

 INC EM_COUNT

 LEA DX,EMERGENCY_DONE
 CALL PRINT_TEXT

 JMP EM_RETURN

EM_INVALID:

 JMP INVALID_SELECTION

EM_RETURN:

 MOV INTERRUPTED,0

 MOV AX,0249h
 OUT 4,AX

 JMP MAIN_MENU

; ==========================================
; FEATURE 6
; MANUAL CONTROL
; ==========================================

MANUAL_MODE:

 MOV INTERRUPTED,0

 CMP FAULT_ACTIVE,0
 JE MANUAL_SHOW

 LEA DX,FAULT_WARNING
 CALL PRINT_TEXT

 JMP MAIN_MENU

MANUAL_SHOW:

 MOV AX,0249h
 OUT 4,AX

 LEA DX,MANUAL_MENU
