 ADD VEHICLE_COUNT,AX

 RET
 ; ==========================================
; FEATURE 11
; REAL-TIME COUNTDOWN
; ==========================================

COUNTDOWN:

 MOV SECONDS_LEFT,AL

 CALL GET_SYSTEM_TIME

 MOV LAST_SECOND,DH

 CALL DISPLAY_REMAINING

COUNT_LOOP:

 CALL CHECK_KEYBOARD

 CMP INTERRUPTED,1
 JE COUNT_FINISH

 CALL GET_SYSTEM_TIME

 CMP DH,LAST_SECOND
 JE COUNT_LOOP

 MOV LAST_SECOND,DH

 CMP SECONDS_LEFT,0
 JE COUNT_FINISH

 DEC SECONDS_LEFT

 CALL DISPLAY_REMAINING

 CMP SECONDS_LEFT,0
 JNE COUNT_LOOP

COUNT_FINISH:

 RET

; ==========================================
; KEYBOARD INPUT DURING COUNTDOWN
; ==========================================

CHECK_KEYBOARD:

 PUSH AX
 PUSH DX

 MOV AH,06h
 MOV DL,0FFh
 INT 21h

 JZ KEY_CHECK_FINISH

 CMP AL,'0'
 JNE CHECK_NUMBERS

 MOV AX,0249h
 OUT 4,AX

 MOV AH,4Ch
 INT 21h

CHECK_NUMBERS:

 CMP AL,'1'
 JB CHECK_LETTERS

 CMP AL,'9'
 JA CHECK_LETTERS

 MOV INTERRUPTED,1

 JMP KEY_CHECK_FINISH

CHECK_LETTERS:

 CMP AL,'A'
 JE INTERRUPT_KEY

 CMP AL,'a'
 JE INTERRUPT_KEY

 CMP AL,'B'
 JE INTERRUPT_KEY

 CMP AL,'b'
 JE INTERRUPT_KEY

 CMP AL,'P'
 JE PEDESTRIAN_KEY

 CMP AL,'p'
 JE PEDESTRIAN_KEY

 JMP KEY_CHECK_FINISH

INTERRUPT_KEY:

 MOV INTERRUPTED,1

 JMP KEY_CHECK_FINISH

PEDESTRIAN_KEY:

 MOV PED_PENDING,1

KEY_CHECK_FINISH:

 POP DX
 POP AX

 RET

; ==========================================
; READ SYSTEM TIME
; ==========================================

GET_SYSTEM_TIME:

 MOV AH,2Ch
 INT 21h

 RET

; ==========================================
; DISPLAY REMAINING TIME
; ==========================================

DISPLAY_REMAINING:

 LEA DX,REMAIN_TEXT
 CALL PRINT_TEXT

 XOR AX,AX

 MOV AL,SECONDS_LEFT

 CALL PRINT_NUMBER

 LEA DX,SECONDS_TEXT
 CALL PRINT_TEXT

 RET

; ==========================================
; NORMAL KEYBOARD INPUT
; ==========================================

READ_KEY:

 MOV AH,01h
 INT 21h

 RET

; ==========================================
; DISPLAY STRING
; ==========================================

PRINT_TEXT:

 MOV AH,09h
 INT 21h

 RET

; ==========================================
; PRINT DECIMAL NUMBER
; INPUT: AX
; ==========================================

PRINT_NUMBER:

 PUSH AX
 PUSH BX
 PUSH CX
 PUSH DX

 MOV BX,10
 XOR CX,CX

 CMP AX,0
 JNE NUMBER_CONVERT

 MOV DL,'0'
 MOV AH,02h
 INT 21h

 JMP NUMBER_FINISH

NUMBER_CONVERT:

 XOR DX,DX

 DIV BX

 PUSH DX

 INC CX

 CMP AX,0
 JNE NUMBER_CONVERT

NUMBER_DISPLAY:

 POP DX

 ADD DL,'0'

 MOV AH,02h
 INT 21h

 DEC CX

 JNZ NUMBER_DISPLAY

NUMBER_FINISH:

 POP DX
 POP CX
 POP BX
 POP AX

 RET

; ==========================================
; EXIT PROGRAM
; ==========================================

EXIT_PROGRAM:

 MOV AX,0249h
 OUT 4,AX

 MOV AH,4Ch
 INT 21h

END
